#![forbid(unsafe_code)]

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum UiLocale {
    Uk,
    En,
    De,
    Fr,
    Es,
    Ko,
    Ja,
    Zh,
}

impl UiLocale {
    pub const ALL: [UiLocale; 8] = [
        UiLocale::Uk,
        UiLocale::En,
        UiLocale::De,
        UiLocale::Fr,
        UiLocale::Es,
        UiLocale::Ko,
        UiLocale::Ja,
        UiLocale::Zh,
    ];

    pub const fn code(self) -> &'static str {
        match self {
            Self::Uk => "uk",
            Self::En => "en",
            Self::De => "de",
            Self::Fr => "fr",
            Self::Es => "es",
            Self::Ko => "ko",
            Self::Ja => "ja",
            Self::Zh => "zh-Hans",
        }
    }

    pub const fn label(self) -> &'static str {
        match self {
            Self::Uk => "🇺🇦 Українська",
            Self::En => "🇬🇧 English",
            Self::De => "🇩🇪 Deutsch",
            Self::Fr => "🇫🇷 Français",
            Self::Es => "🇪🇸 Español",
            Self::Ko => "🇰🇷 한국어",
            Self::Ja => "🇯🇵 日本語",
            Self::Zh => "🇨🇳 简体中文",
        }
    }

    pub fn parse(value: &str) -> Self {
        let value = value.trim().to_ascii_lowercase();
        if value.starts_with("uk") {
            Self::Uk
        } else if value.starts_with("de") {
            Self::De
        } else if value.starts_with("fr") {
            Self::Fr
        } else if value.starts_with("es") {
            Self::Es
        } else if value.starts_with("ko") {
            Self::Ko
        } else if value.starts_with("ja") {
            Self::Ja
        } else if value.starts_with("zh") {
            Self::Zh
        } else {
            Self::En
        }
    }
}

